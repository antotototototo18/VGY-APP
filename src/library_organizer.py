from __future__ import annotations

from collections import defaultdict
from typing import Dict, List

from src.spotify_tools import get_user_spotify_client, _fetch_liked_tracks


def create_curated_playlists_by_artist(min_tracks: int = 8) -> None:
    """
    Create one playlist per artist with at least `min_tracks` liked songs.
    """
    sp = get_user_spotify_client()
    liked_items = _fetch_liked_tracks(sp, limit=2000)

    artist_buckets: Dict[str, List[str]] = defaultdict(list)

    for item in liked_items:
        track = item["track"]
        artists = track["artists"]
        if not artists:
            continue

        main_artist = artists[0]["name"]
        artist_buckets[main_artist].append(track["id"])

    user = sp.current_user()
    user_id = user["id"]

    for artist, ids in artist_buckets.items():
        if len(ids) < min_tracks:
            continue

        name = f"Vignity – {artist}"
        desc = f"Curated liked songs by {artist} (generated by Vignity)."
        pl = sp.user_playlist_create(user_id, name, public=False, description=desc)
        sp.playlist_add_items(pl["id"], ids)
